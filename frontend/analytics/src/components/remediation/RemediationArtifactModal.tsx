import { useState } from "react";
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogDescription,
} from "@/components/ui/dialog";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { toast } from "sonner";
import { FileText, Copy, Check, Sparkles } from "lucide-react";
import type { RemediationActionItem } from "@/types";

interface RemediationArtifactModalProps {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  action: RemediationActionItem | null;
}

export function RemediationArtifactModal({
  open,
  onOpenChange,
  action,
}: RemediationArtifactModalProps) {
  const [copied, setCopied] = useState(false);

  if (!action) return null;

  const artifact = action.artifacts?.[0];
  const title = artifact?.title || `Generated Artifact for ${action.title}`;
  const contentType = artifact?.contentType || "text/markdown";
  const contentBody =
    artifact?.contentBody ||
    `# Generated ${action.type}\n\nAutomated execution output for Dyvin AI platform optimization.\n\n- Organization: ${action.organizationId}\n- Status: ${action.status}\n- Priority: ${action.priority}\n- Created: ${action.createdAt}\n\nCanonical brand entity schema alignment generated successfully.`;

  const handleCopy = () => {
    navigator.clipboard.writeText(contentBody);
    setCopied(true);
    toast.success("Artifact content copied to clipboard");
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="max-w-2xl bg-surface border-border p-6 space-y-5">
        <DialogHeader className="space-y-1.5 border-b border-border/60 pb-3">
          <div className="flex items-center justify-between">
            <DialogTitle className="flex items-center gap-2 text-foreground text-base font-semibold">
              <div className="p-1.5 rounded-md bg-emerald-500/10 text-emerald-500">
                <FileText className="size-4" />
              </div>
              {title}
            </DialogTitle>
            <Badge variant="outline" className="text-[10px] font-mono text-emerald-600 dark:text-emerald-400 bg-emerald-500/10 border-emerald-500/25">
              {contentType}
            </Badge>
          </div>
          <DialogDescription className="text-xs text-muted-foreground">
            Synthesized remediation artifact generated by autonomous background worker.
          </DialogDescription>
        </DialogHeader>

        <div className="space-y-2">
          <div className="flex items-center justify-between text-xs">
            <span className="font-semibold text-muted-foreground uppercase text-[11px] tracking-wider">
              Output Payload:
            </span>
            <Button
              variant="ghost"
              size="sm"
              className="h-7 text-[11px] gap-1 px-2 text-muted-foreground hover:text-foreground"
              onClick={handleCopy}
            >
              {copied ? <Check className="size-3 text-emerald-500" /> : <Copy className="size-3" />}
              {copied ? "Copied" : "Copy Payload"}
            </Button>
          </div>
          <pre className="p-4 rounded-xl bg-surface-subtle/60 border border-border text-xs font-mono text-foreground overflow-x-auto max-h-72 leading-relaxed">
            {contentBody}
          </pre>
        </div>

        <div className="flex items-center justify-end gap-2 pt-2 border-t border-border/60">
          <Button variant="outline" size="sm" onClick={() => onOpenChange(false)}>
            Close
          </Button>
        </div>
      </DialogContent>
    </Dialog>
  );
}
